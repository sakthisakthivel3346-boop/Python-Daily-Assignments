# Student Marks Management using List

# 1. Get marks of 5 students
marks = []

for i in range(5):
    mark = int(input(f"Enter mark of student {i+1}: "))
    marks.append(mark)

# 2. Display all marks
print("\nAll Student Marks:", marks)

# 3. Add a new student's mark using append()
new_mark = int(input("\nEnter new student's mark: "))
marks.append(new_mark)
print("After append:", marks)

# 4. Insert a mark at the second position
insert_mark = int(input("Enter mark to insert at second position: "))
marks.insert(1, insert_mark)
print("After insert:", marks)

# 5. Remove a particular mark
remove_mark = int(input("Enter mark to remove: "))
if remove_mark in marks:
    marks.remove(remove_mark)
    print("After remove:", marks)
else:
    print("Mark not found!")

# 6. Display highest and lowest marks
print("\nHighest Mark:", max(marks))
print("Lowest Mark:", min(marks))

# 7. Calculate total and average
total = sum(marks)
average = total / len(marks)

print("Total Marks:", total)
print("Average Marks:", average)

# 8. Sort marks in ascending order
marks.sort()
print("Ascending Order:", marks)

# 9. Count students who scored above 75
count = 0
for mark in marks:
    if mark > 75:
        count += 1

print("Students scored above 75:", count)

# 10. Display marks greater than or equal to 50
print("Marks greater than or equal to 50:")
for mark in marks:
    if mark >= 50:
        print(mark)

# Task 2: Shopping Cart Management using Tuple

# 1. Create a tuple containing 5 product names
products = ("Laptop", "Mobile", "Headphones", "Keyboard", "Mouse")

# 2. Display all products
print("All Products:", products)

# 3. Display first and last products using indexing
print("\nFirst Product:", products[0])
print("Last Product:", products[-1])

# 4. Display first 3 products using slicing
print("\nFirst 3 Products:", products[:3])

# 5. Check whether a product is available using 'in' operator
search_product = input("\nEnter product name to search: ")

if search_product in products:
    print(search_product, "is available")
else:
    print(search_product, "is not available")

# 6. Count how many times a product appears using count()
count_product = input("\nEnter product name to count: ")
print("Product Count:", products.count(count_product))

# 7. Find the position of a product using index()
index_product = input("\nEnter product name to find position: ")

if index_product in products:
    print("Product Position:", products.index(index_product))
else:
    print("Product not found")

# 8. Concatenate another tuple containing 2 new products
new_products = ("Smart Watch", "Tablet")
