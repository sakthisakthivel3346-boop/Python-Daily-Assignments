# Task 1: Unique Number Analyzer using Set

# 1. Get 10 numbers from the user
numbers = set()

for i in range(10):
    num = int(input(f"Enter number {i+1}: "))
    numbers.add(num)

# 2. Display all unique numbers
print("\nUnique Numbers:", numbers)

# 3. Add a new number using add()
new_num = int(input("\nEnter a new number to add: "))
numbers.add(new_num)
print("After adding:", numbers)

# 4. Remove a number using discard()
remove_num = int(input("Enter a number to remove: "))
numbers.discard(remove_num)
print("After removing:", numbers)

# 5. Check whether a number exists using in
search_num = int(input("Enter a number to search: "))

if search_num in numbers:
    print(search_num, "exists in the set")
else:
    print(search_num, "does not exist in the set")

# 6. Create another set containing 5 numbers
set2 = set()

for i in range(5):
    num = int(input(f"Enter second set number {i+1}: "))
    set2.add(num)

print("\nSecond Set:", set2)

# 7. Find union of both sets
print("Union:", numbers.union(set2))

# 8. Find intersection of both sets
print("Intersection:", numbers.intersection(set2))

# 9. Find difference between two sets
print("Difference:", numbers.difference(set2))

# 10. Display total number of unique elements
print("Total Unique Elements:", len(numbers))

